#!/usr/bin/env python3
"""Regenerate the AUTO section of CLAUDE.md from the code (stdlib only, no network, no model).

Run by: the SessionStart hook (.claude/settings.json) and the git pre-commit hook (.githooks/pre-commit).
Only the text between the AUTO markers changes; everything else in CLAUDE.md is hand-written.
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- AUTO:START (generated by scripts/update-claude-md.py - do not edit by hand) -->", "<!-- AUTO:END -->"


def flow_section() -> list[str]:
    out = ["### helper/flow.py"]
    p = ROOT / "helper" / "flow.py"
    if not p.exists():
        return out + ["(missing)"]
    src = p.read_text(encoding="utf-8")
    tree = ast.parse(src)
    out.append("Classes and their methods (grep the name to find the code):")
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            doc = (ast.get_docstring(node) or "").strip().splitlines()
            first = doc[0].strip() if doc else ""
            methods = [n.name for n in node.body if isinstance(n, ast.FunctionDef) and not (n.name.startswith("__"))]
            out.append(f"- `{node.name}`" + (f" - {first}" if first else "") + (f": {', '.join(methods)}" if methods else ""))
    funcs = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
    if funcs:
        out.append(f"- module functions: {', '.join(funcs)}")
    flags = []
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and getattr(n.func, "attr", "") == "add_argument":
            name = next((a.value for a in n.args if isinstance(a, ast.Constant) and isinstance(a.value, str)), None)
            help_ = next((k.value.value for k in n.keywords if k.arg == "help" and isinstance(k.value, ast.Constant)), "")
            if name:
                flags.append(f"`{name}` {str(help_).split('.')[0].strip()}".strip())
    if flags:
        out.append("CLI flags: " + " | ".join(flags))
    return out


def first_doc_line(path: Path) -> str:
    text = path.read_text(encoding="utf-8", errors="ignore")
    m = re.match(r"\s*/\*\*(.*?)\*/", text, re.S)   # only a header comment at the very top of the file
    if not m:
        return ""
    for line in m.group(1).splitlines():
        line = line.strip().lstrip("*").strip()
        if line:
            return line
    return ""


def api_section() -> list[str]:
    out = ["### api/ (Vercel functions)"]
    for f in sorted((ROOT / "api").glob("*.js")):
        d = first_doc_line(f)
        out.append(f"- `api/{f.name}`" + (f" - {d}" if d else ""))
    srv = sorted(p.name for p in (ROOT / "server").glob("*.js"))
    if srv:
        out.append("- `server/` shared logic: " + ", ".join(srv))
    return out


def web_section() -> list[str]:
    out = ["### Web app routes (src/App.tsx)"]
    app = ROOT / "src" / "App.tsx"
    if app.exists():
        routes = re.findall(r'<Route\s+(?:index|path="([^"]*)")\s+element=\{<(\w+)', app.read_text(encoding="utf-8"))
        # `index` routes have empty path
        routes = [(p or "(index)", c) for p, c in routes]
        out.append(", ".join(f"`{p}` -> {c}" for p, c in routes))
    comps = sorted(p.stem for p in (ROOT / "src" / "components").glob("*.tsx"))
    if comps:
        out.append("Components: " + ", ".join(comps))
    return out


def misc_section() -> list[str]:
    out = ["### Database and scripts"]
    mig = sorted(p.name for p in (ROOT / "supabase" / "migrations").glob("*.sql"))
    if mig:
        out.append(f"Supabase migrations ({len(mig)}), newest last: " + ", ".join(mig[-6:]))
    pkg = ROOT / "package.json"
    if pkg.exists():
        scripts = json.loads(pkg.read_text(encoding="utf-8")).get("scripts", {})
        out.append("package.json scripts: " + ", ".join(f"`{k}`" for k in scripts))
    docs = sorted(p.name for p in (ROOT / "docs").glob("*.md"))
    if docs:
        out.append("Docs: " + ", ".join(f"`docs/{d}`" for d in docs))
    return out


def build() -> str:
    parts = [START, "## Auto-generated map (kept current by script)", ""]
    for sec in (flow_section(), api_section(), web_section(), misc_section()):
        parts += sec + [""]
    parts.append(END)
    return "\n".join(parts)


def main() -> int:
    target = ROOT / "CLAUDE.md"
    text = target.read_text(encoding="utf-8") if target.exists() else ""
    block = build()
    if START in text and END in text:
        new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    else:
        new = text.rstrip() + "\n\n" + block + "\n"
    if new != text:
        target.write_text(new, encoding="utf-8")
        print("CLAUDE.md updated")
    else:
        print("CLAUDE.md already current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
